"""Paste-ready X3 text for paper_2.0/srw/main_v2.tex, every number from CSVs. Writes results/x3/paper_insert.tex; edits no paper."""
from pathlib import Path

import pandas as pd

R = Path(__file__).resolve().parents[1] / "results"
C, L = pd.read_csv(R / "x3/coefficients.csv"), pd.read_csv(R / "x2/coefficients.csv")
Q = pd.read_csv(R / "x3/questions.csv")
g = lambda D, m, y: D[(D.model == m) & (D.outcome == y)].iloc[0]
s = lambda v: f"${v:+.2f}$"
c = lambda r: f"{s(r.b_obscurity)} [{s(r.obscurity_lo)}, {s(r.obscurity_hi)}]"
p, x = g(C, "two judges", "both"), g(C, "regex, 20 short replies", "regex24")
k = lambda n: f"{int(n):,}".replace(",", "{,}")
rows = "\n".join(f"{n} & {k(g(C, m, 'both').n)} & {c(g(C, m, 'both'))} & {c(g(C, m if m != 'two judges' else 'regex, 20 short replies', 'regex24'))} \\\\" for n, m in
                 (("All tenths", "two judges"), ("Tenths 2 to 9", "deciles 2 to 9 only"), ("Without three relations", "without country, capital and sport"), ("Knowledge in 11 levels", "knowledge score as 11 levels")))
t = f"""% GENERATED by scripts/x3_insert.py from results/x3/*.csv. Not in any paper yet.
% ---- paragraph after "The Whole Popularity Range"
\\paragraph{{A Second Model.}} We repeated this check on Gemma-2-9B-it with the same questions, asked with the prompt that invites abstaining, because Gemma rarely says \\idk{{}} without it (the plan was recorded before the run). Knowledge is Gemma's own. Obscurity again raises abstention: {c(p)}, {c(g(C, 'deciles 2 to 9 only', 'both'))} without the extreme tenths, and {c(x)} with the regex. Predicted abstention is {p.predicted_at_popularity_90th:.2f} at the 90th percentile of popularity and {p.predicted_at_popularity_10th:.2f} at the 10th. Prompts differ between the two models, so the sizes are not comparable. The result holds for Llama-3.1-8B-Instruct and Gemma-2-9B-it on PopQA.

% ---- appendix table
\\begin{{table}}[h]
\\centering
\\small\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{tabular}}{{lrll}}
\\toprule
Gemma-2-9B-it & $n$ & Two judges & Regex \\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\caption{{As the Llama table, for Gemma-2-9B-it with the prompt that invites abstaining. The relation ``{p.relations_dropped_constant}'' is dropped from the fits because no reply abstains there (34 questions). 95\\% intervals resample whole relations (5,000 draws{'; 26 draws of the 11-level two-judge fit and 1 of the regex fit did not converge and are dropped' if g(C, 'knowledge score as 11 levels', 'both').draws_not_converged == 26 and g(C, 'knowledge score as 11 levels', 'regex24').draws_not_converged == 1 else ''}).}}
\\label{{tab:gemmarange}}
\\end{{table}}
% ---- Limitations: replace "We study one model in depth, on one dataset" with "We study one model in depth and a second in one check, on one dataset"
"""
(R / "x3/paper_insert.tex").write_text(t, encoding="utf-8"); print(t[:1400])
print(p.relations_dropped_constant, Q[Q.prop == "color"][["both", "regex24"]].mean().to_dict(), (Q.prop == "color").sum())
